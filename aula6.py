#Operadores de relacionais
# > - maior que
# < - menor que
idade = 21

if (idade > - 18):
    print("Maior.")
else:
    print("Menor.")

# < - menor que
idade = 21

if (idade < - 18):
    print("Maior.")
else:
    print("Menor.")

# >= maior ou igual
idade = 21

if (idade >=  18):
    print("Maior.")
else:
    print("Menor.")

# <= menor ou igual
idade = 21

if (idade <= 18):
    print("Maior.")
else:
    print("Menor.")

#Operadores de igualdade
# == igual igual
idade = 18

if (idade == 18):
    print("É Igual.")
else:
    print("Diferente.")

# != diferente de
idade = 21

if (idade != 18):
    print("Diferente.")
else:
    print("Não é igual.")